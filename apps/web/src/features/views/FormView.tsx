// apps/web/src/features/views/FormView.tsx
// 表单视图：居中的公开填写表单，提交后创建记录

import { useMemo, useState } from "react";
import { useFields, useTables, useGXMutations } from "../../api/hooks";
import type { CellValue, FieldDTO } from "@gx/shared-types";
import { Button, EmptyState, Spinner, toast } from "../../components/ui";
import { FieldInput, type ViewProps } from "./field-controls";
import { autoFormFields } from "./form-config";

export default function FormView({
  baseId,
  tableId,
  viewId,
  view,
  permissions,
}: ViewProps) {
  const { data: fieldsRes } = useFields(tableId);
  const { data: tables } = useTables(baseId);
  const m = useGXMutations();

  const table = tables?.find((t) => t.id === tableId);
  const fields = fieldsRes ?? [];

  // 表单字段：配置优先；为空则用全部非系统字段自动生成并提示
  const { formFields, autoGenerated } = useMemo(() => {
    const cfg = view.config.formFields ?? [];
    if (cfg.length > 0) {
      return { formFields: cfg, autoGenerated: false };
    }
    // 与设置面板共用 autoFormFields，保证「未配置时看到什么」和「配置区初始草稿」一致
    return { formFields: autoFormFields(fields), autoGenerated: true };
  }, [view.config.formFields, fields]);

  const fieldMap = useMemo(() => {
    const map = new Map<string, FieldDTO>();
    fields.forEach((f) => map.set(f.id, f));
    return map;
  }, [fields]);

  const [values, setValues] = useState<Record<string, CellValue>>({});
  const [submitted, setSubmitted] = useState(false);
  const [submitting, setSubmitting] = useState(false);

  const visibleFields = formFields.filter((ff) => !ff.hidden && fieldMap.has(ff.fieldId));

  const setValue = (fieldId: string, v: CellValue) =>
    setValues((prev) => ({ ...prev, [fieldId]: v }));

  const handleSubmit = async () => {
    // 必填校验
    for (const ff of visibleFields) {
      const f = fieldMap.get(ff.fieldId)!;
      const v = values[ff.fieldId];
      const empty =
        v == null ||
        v === "" ||
        (Array.isArray(v) && v.length === 0);
      if (ff.required && empty) {
        toast(`「${ff.label || f.name}」为必填项`, "error");
        return;
      }
    }
    if (!permissions.canEditData) {
      toast("当前角色无权提交", "error");
      return;
    }
    setSubmitting(true);
    try {
      await m.createRecord.mutateAsync({ tableId, fields: { ...values }, viewId });
      setSubmitted(true);
      setValues({});
    } catch (err) {
      toast((err as Error).message || "提交失败", "error");
    } finally {
      setSubmitting(false);
    }
  };

  if (!permissions.canEditData) {
    return (
      <div className="flex h-full items-center justify-center p-gx-lg">
        <EmptyState icon="lock" title="无权提交" description="当前角色没有填写此表单的权限。" />
      </div>
    );
  }

  if (submitted) {
    return (
      <div className="flex h-full items-center justify-center p-gx-lg">
        <EmptyState
          icon="check"
          title="提交成功"
          description="感谢你的填写，记录已保存。"
          action={
            <Button variant="primary" className="mt-2" onClick={() => setSubmitted(false)}>
              再填一份
            </Button>
          }
        />
      </div>
    );
  }

  if (fields.length === 0) {
    return (
      <div className="flex h-full items-center justify-center p-gx-lg">
        <Spinner />
      </div>
    );
  }

  return (
    <div className="h-full overflow-auto p-gx-lg">
      <div className="mx-auto w-full" style={{ maxWidth: 560 }}>
        <div className="rounded-gx-xl border border-gx-border bg-gx-surface p-gx-lg shadow-sm">
          <h2 className="text-gx-18 font-semibold text-gx-text-primary">
            {view.config.formTitle || table?.name || "表单"}
          </h2>
          {view.config.formDescription && (
            <p className="mt-1 text-gx-13 text-gx-text-tertiary">{view.config.formDescription}</p>
          )}
          {autoGenerated && (
            <p className="mt-2 rounded-gx-sm bg-gx-accent-bg px-2 py-1 text-gx-12 text-gx-accent">
              提示：这份表单尚未配置字段，已按全部字段自动生成。要调整字段、顺序、必填或标题，点视图名称旁的「⋯」→「视图设置」。
            </p>
          )}

          <div className="mt-4 flex flex-col gap-4">
            {visibleFields.map((ff) => {
              const f = fieldMap.get(ff.fieldId)!;
              return (
                <div key={ff.fieldId} className="flex flex-col gap-1">
                  <label className="text-gx-13 font-medium text-gx-text-primary">
                    {ff.label || f.name}
                    {ff.required && <span className="ml-0.5 text-gx-danger">*</span>}
                  </label>
                  {ff.help && <div className="text-gx-12 text-gx-text-hint">{ff.help}</div>}
                  <FieldInput field={f} value={values[ff.fieldId] ?? null} onChange={(v) => setValue(ff.fieldId, v)} />
                </div>
              );
            })}
          </div>

          <div className="mt-6 flex justify-end">
            <Button variant="primary" onClick={handleSubmit} loading={submitting}>
              提交
            </Button>
          </div>
        </div>
      </div>
    </div>
  );
}
